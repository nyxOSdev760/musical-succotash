#!/usr/bin/env python3
"""Writes SOURCE.md: the file tree followed by every source file in full."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE_EXT = {".swift", ".metal", ".plist", ".json", ".pbxproj", ".xcscheme", ".xcworkspacedata", ".yml", ".py", ".md"}
SKIP_DIRS = {".git", "build", "dist", "Payload", "DerivedData"}
SKIP_FILES = {"SOURCE.md"}
LANG = {".swift": "swift", ".metal": "cpp", ".plist": "xml", ".json": "json", ".yml": "yaml", ".py": "python",
        ".xcscheme": "xml", ".xcworkspacedata": "xml", ".pbxproj": "", ".md": "markdown"}

def walk(base):
    entries = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            entries.append(os.path.relpath(os.path.join(dirpath, f), ROOT))
    return entries

def tree(paths):
    lines = ["."]
    nodes = {}
    for p in paths:
        cur = nodes
        for part in p.split(os.sep):
            cur = cur.setdefault(part, {})
    def render(node, prefix):
        items = sorted(node.items(), key=lambda kv: (len(kv[1]) == 0, kv[0].lower()))
        for i, (name, child) in enumerate(items):
            last = i == len(items) - 1
            lines.append(prefix + ("└── " if last else "├── ") + name + ("/" if child else ""))
            render(child, prefix + ("    " if last else "│   "))
    render(nodes, "")
    return "\n".join(lines)

all_files = [p for p in walk(ROOT) if os.path.basename(p) not in SKIP_FILES]
listed = [p for p in all_files if os.path.splitext(p)[1] in INCLUDE_EXT]
out = ["# Cutline — complete source", "",
       "Generated by `tools/make_source_listing.py`. Binary assets (app icon PNG, built IPA) are in the repository but not inlined.", "",
       "## File tree", "", "```", tree(all_files), "```", ""]
for p in listed:
    ext = os.path.splitext(p)[1]
    with open(os.path.join(ROOT, p), encoding="utf-8") as fh:
        body = fh.read()
    fence = "````" if "```" in body else "```"
    out += [f"## `{p}`", "", f"{fence}{LANG.get(ext, '')}", body.rstrip("\n"), fence, ""]
with open(os.path.join(ROOT, "SOURCE.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print(f"SOURCE.md: {len(listed)} files inlined")
